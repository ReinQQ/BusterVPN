/**
 * Matches an arbitrary string (domain, process name, url, or log message) to a service.
 * @param {string} text
 * @returns {typeof SERVICES[keyof typeof SERVICES] | null}
 */
export function matchService(text) {
  if (!text || typeof text !== 'string') return null;
  const lower = text.toLowerCase().trim();

  // 1. Direct key match
  if (SERVICES[lower]) {
    return SERVICES[lower];
  }

  // 2. Exact executable check (e.g. "discord.exe" -> discord)
  for (const s of Object.values(SERVICES)) {
    for (const kw of s.keywords) {
      if (lower === kw || lower === `${kw}.exe`) {
        return s;
      }
    }
  }

  // 3. Substring / domain word boundary search
  for (const s of Object.values(SERVICES)) {
    for (const kw of s.keywords) {
      if (lower.includes(kw)) {
        return s;
      }
    }
  }

  return null;
}
