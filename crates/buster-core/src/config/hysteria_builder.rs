use crate::config::ConfigBuildError;
use crate::models::{
    Hysteria2ClientConfig, ParsedServer, RoutingAction, RoutingMatchType, RoutingMode, RoutingRule,
    PRIVATE_IPV4_CIDRS, PRIVATE_IPV6_CIDRS,
};
use crate::parsing::validation::is_valid_port;

pub const DEFAULT_HYSTERIA_TUN_NAME: &str = "BusterVPN";
pub const HYSTERIA_TUN_MTU: u32 = 1400; // Leaves room for QUIC + IP/UDP headers
pub const HYSTERIA_TUN_DNS: &[&str] = &["1.1.1.1", "8.8.8.8"];

#[derive(Debug, Clone)]
pub struct HysteriaBuildParams<'a> {
    pub profile: &'a ParsedServer,
    pub routing_mode: RoutingMode,
    pub routing_rules: &'a [RoutingRule],
    pub bypass_local_networks: bool,
    pub socks_port: u16,
    pub http_port: u16,
    pub tun_name: &'a str,
    pub server_addresses: &'a [String],
}

impl<'a> HysteriaBuildParams<'a> {
    pub fn new(
        profile: &'a ParsedServer,
        routing_mode: RoutingMode,
        server_addresses: &'a [String],
    ) -> Self {
        Self {
            profile,
            routing_mode,
            routing_rules: &[],
            bypass_local_networks: true,
            socks_port: 10808,
            http_port: 10809,
            tun_name: DEFAULT_HYSTERIA_TUN_NAME,
            server_addresses,
        }
    }
}

pub fn build_hysteria_config(params: &HysteriaBuildParams) -> Result<String, ConfigBuildError> {
    let client = params
        .profile
        .hysteria2
        .as_ref()
        .ok_or(ConfigBuildError::MissingHysteriaConfig)?;

    client.validate()?;

    if params.routing_mode.has_local_proxy()
        && (!is_valid_port(params.socks_port as u32) || !is_valid_port(params.http_port as u32))
    {
        return Err(ConfigBuildError::InvalidProxyPorts(
            params.socks_port,
            params.http_port,
        ));
    }

    let mut writer = YamlBuilder::new();
    writer.line("# Generated by BusterVPN. Contains credentials; do not share.");
    writer.line(&format!("server: {}", quote(&client.server_address)));
    writer.line(&format!("auth: {}", quote(&client.auth)));

    writer.line("tls:");
    writer.indent();
    if let Some(sni) = &client.sni {
        if !sni.trim().is_empty() {
            writer.line(&format!("sni: {}", quote(sni)));
        }
    }
    writer.line(&format!("insecure: {}", client.insecure));
    if let Some(pin) = &client.pin_sha256 {
        if !pin.trim().is_empty() {
            writer.line(&format!("pinSHA256: {}", quote(pin)));
        }
    }
    if let Some(ech) = &client.ech {
        if !ech.trim().is_empty() {
            writer.line(&format!("ech: {}", quote(ech)));
        }
    }
    writer.outdent();

    if let Some(obfs_type) = &client.obfs_type {
        writer.line("obfs:");
        writer.indent();
        writer.line(&format!("type: {}", quote(obfs_type)));
        writer.line(&format!("{}:", obfs_type));
        writer.indent();
        writer.line(&format!(
            "password: {}",
            quote(client.obfs_password.as_deref().unwrap_or(""))
        ));
        writer.outdent();
        writer.outdent();
    }

    if client.up_mbps.is_some() || client.down_mbps.is_some() {
        writer.line("bandwidth:");
        writer.indent();
        if let Some(up) = client.up_mbps {
            writer.line(&format!("up: {}", quote(&format!("{} mbps", up))));
        }
        if let Some(down) = client.down_mbps {
            writer.line(&format!("down: {}", quote(&format!("{} mbps", down))));
        }
        writer.outdent();
    }

    if params.routing_mode.has_local_proxy() {
        writer.line("socks5:");
        writer.indent();
        writer.line(&format!("listen: {}", quote(&format!("127.0.0.1:{}", params.socks_port))));
        writer.outdent();

        writer.line("http:");
        writer.indent();
        writer.line(&format!("listen: {}", quote(&format!("127.0.0.1:{}", params.http_port))));
        writer.outdent();
    }

    if params.routing_mode.has_tun() {
        write_tun(&mut writer, params, client)?;
    }

    Ok(writer.build())
}

fn write_tun(
    writer: &mut YamlBuilder,
    params: &HysteriaBuildParams,
    _client: &Hysteria2ClientConfig,
) -> Result<(), ConfigBuildError> {
    let mut ipv4_exclusions = Vec::new();
    let mut ipv6_exclusions = Vec::new();

    // 1. Server addresses to prevent QUIC loop
    for addr in params.server_addresses {
        let trimmed = addr.trim();
        if !trimmed.is_empty() {
            let cidr = if trimmed.contains('/') {
                trimmed.to_string()
            } else {
                format!("{}/32", trimmed)
            };
            ipv4_exclusions.push(cidr);
        }
    }

    // 2. Local network exclusions
    if params.bypass_local_networks {
        for cidr in PRIVATE_IPV4_CIDRS {
            ipv4_exclusions.push(cidr.to_string());
        }
        for cidr in PRIVATE_IPV6_CIDRS {
            ipv6_exclusions.push(cidr.to_string());
        }
    }

    // 3. User direct routing rules (IP CIDR)
    for rule in params.routing_rules.iter().filter(|r| r.enabled) {
        if rule.match_type == RoutingMatchType::IpCidr && rule.action == RoutingAction::Direct {
            if rule.value.contains(':') {
                ipv6_exclusions.push(rule.value.clone());
            } else {
                ipv4_exclusions.push(rule.value.clone());
            }
        }
    }

    ipv4_exclusions.sort();
    ipv4_exclusions.dedup();
    ipv6_exclusions.sort();
    ipv6_exclusions.dedup();

    writer.line("tun:");
    writer.indent();
    writer.line(&format!("name: {}", quote(params.tun_name)));
    writer.line(&format!("mtu: {}", HYSTERIA_TUN_MTU));

    writer.line("dns:");
    writer.indent();
    for dns in HYSTERIA_TUN_DNS {
        writer.line(&format!("- {}", quote(dns)));
    }
    writer.outdent();

    writer.line("timeout: 60s");
    writer.line("address:");
    writer.indent();
    writer.line("ipv4: \"100.100.100.101/30\"");
    writer.line("ipv6: \"fd88:88:88:88::1/126\"");
    writer.outdent();

    writer.line("route:");
    writer.indent();
    writer.line("ipv4:");
    writer.indent();
    writer.line("- \"0.0.0.0/0\"");
    writer.outdent();
    writer.line("ipv6:");
    writer.indent();
    writer.line("- \"::/0\"");
    writer.outdent();

    if !ipv4_exclusions.is_empty() {
        writer.line("ipv4Exclude:");
        writer.indent();
        for cidr in ipv4_exclusions {
            writer.line(&format!("- {}", quote(&cidr)));
        }
        writer.outdent();
    }

    if !ipv6_exclusions.is_empty() {
        writer.line("ipv6Exclude:");
        writer.indent();
        for cidr in ipv6_exclusions {
            writer.line(&format!("- {}", quote(&cidr)));
        }
        writer.outdent();
    }

    writer.outdent(); // route
    writer.outdent(); // tun

    Ok(())
}

fn quote(val: &str) -> String {
    serde_json::to_string(val).unwrap_or_else(|_| format!("\"{}\"", val))
}

struct YamlBuilder {
    buffer: String,
    indent_level: usize,
}

impl YamlBuilder {
    fn new() -> Self {
        Self {
            buffer: String::new(),
            indent_level: 0,
        }
    }

    fn indent(&mut self) {
        self.indent_level += 1;
    }

    fn outdent(&mut self) {
        if self.indent_level > 0 {
            self.indent_level -= 1;
        }
    }

    fn line(&mut self, text: &str) {
        for _ in 0..self.indent_level * 2 {
            self.buffer.push(' ');
        }
        self.buffer.push_str(text);
        self.buffer.push('\n');
    }

    fn build(self) -> String {
        self.buffer
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parsing::hysteria2::parse_hysteria2;

    #[test]
    fn test_hysteria_tun_mtu_and_exclusions() {
        let uri = "hysteria2://secret@example.com:443?sni=example.com#HY";
        let parsed = parse_hysteria2(uri).expect("Parse HY2");

        let server_addrs = vec!["144.31.104.143".to_string()];
        let params = HysteriaBuildParams::new(
            &parsed,
            RoutingMode::TunAndSystemProxy,
            &server_addrs,
        );

        let yaml = build_hysteria_config(&params).expect("Build YAML");

        // Verify MTU 1400
        assert!(yaml.contains("mtu: 1400"));
        // Verify TUN name
        assert!(yaml.contains("name: \"BusterVPN\""));
        // Verify local proxy ports
        assert!(yaml.contains("listen: \"127.0.0.1:10808\""));
        assert!(yaml.contains("listen: \"127.0.0.1:10809\""));
        // Verify server address excluded to prevent loop
        assert!(yaml.contains("- \"144.31.104.143/32\""));
    }
}
